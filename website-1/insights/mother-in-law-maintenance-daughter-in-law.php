<p>Family relationships in India carry strong expectations of mutual care. A particular situation arises when a widow obtains a government job on <strong>compassionate grounds</strong> after her husband's death, and her husband's elderly mother depends on her. Can the mother-in-law claim maintenance?</p>
<h2>What is a compassionate appointment?</h2>
<p>When a government employee dies in service, a family member may be given a job so that the family is not left destitute. The appointment is meant to support <strong>the whole family</strong> of the deceased employee, not only the person appointed.</p>
<h2>The mother-in-law's claim</h2>
<p>Ordinarily, a daughter-in-law has no general legal duty to maintain her parents-in-law. But where she has obtained a job on compassionate grounds in place of her deceased husband, courts have taken the view that she carries a responsibility towards the dependants of the deceased employee, including his mother.</p>
<p>In such cases, courts have directed the daughter-in-law to pay a fixed monthly amount to her mother-in-law as maintenance. In one reported case, the amount was ₹10,000 per month. Often, the undertaking given while seeking the compassionate appointment is an important factor.</p>
<h2>What courts consider</h2>
<ul>
<li>Whether the job was obtained on compassionate grounds because of the son's death</li>
<li>Any undertaking given to support the family</li>
<li>The mother-in-law's age, health and other means of support</li>
<li>The daughter-in-law's income and her own responsibilities, including her children</li>
</ul>
<h2>Conclusion</h2>
<p>A compassionate appointment comes with a responsibility towards the family it was meant to support. Courts try to balance the daughter-in-law's own needs with the welfare of an elderly, dependent mother-in-law. The outcome in each case depends on its facts.</p>
