<p>For NRIs, dealing with family property rights in India can feel daunting. This guide gives you the basics so you can protect your interests from wherever you live.</p>
<h2>Which law applies to you?</h2>
<p>Inheritance in India depends largely on religion and personal law:</p>
<ul>
<li><strong>Hindus, Sikhs, Jains and Buddhists:</strong> the Hindu Succession Act, 1956, under which daughters and sons have equal rights.</li>
<li><strong>Muslims:</strong> Muslim personal law (Shariat), which sets fixed shares for heirs.</li>
<li><strong>Christians and Parsis:</strong> the Indian Succession Act, 1925.</li>
<li><strong>Marriages under the Special Marriage Act, 1954:</strong> succession is generally governed by the Indian Succession Act.</li>
</ul>
<h2>Financial and tax points</h2>
<ul>
<li><strong>FEMA:</strong> NRIs can inherit any property, including agricultural land, but can buy only residential or commercial property. Sale proceeds can be repatriated within the limits and conditions set by the RBI.</li>
<li><strong>Income tax:</strong> inheritance itself is not taxed in India, but rental income and capital gains on sale are. TDS applies when an NRI sells property.</li>
<li><strong>Your country of residence:</strong> check how your home country taxes Indian income and assets; the Double Taxation Avoidance Agreement may help.</li>
</ul>
<h2>Essential tools</h2>
<ul>
<li><strong>Power of attorney:</strong> appoint someone you trust to manage your property, deal with offices and courts, and complete transactions for you.</li>
<li><strong>Keep documents current:</strong> legal heir certificate, patta transfer and mutation after inheritance, and a regular check of the Encumbrance Certificate.</li>
<li><strong>Make a will:</strong> a will for your Indian assets avoids disputes among your heirs later.</li>
</ul>
<h2>Remember</h2>
<ul>
<li>Property left unattended is vulnerable to encroachment and fraud. Act early if something looks wrong.</li>
<li>Family arrangements should be documented and registered, not left as verbal understandings.</li>
<li>Get advice from a lawyer experienced in NRI property matters before signing anything.</li>
</ul>
