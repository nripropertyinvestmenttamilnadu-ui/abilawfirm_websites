<p>Marriage is a legal relationship that carries rights and obligations. Under the Hindu Marriage Act, 1955, some marriages are void from the start. For years, an important question was whether a spouse in a void marriage could still claim permanent alimony or maintenance.</p>
<h2>When is a marriage void?</h2>
<p>Under Section 11 of the Act, a marriage is void, for example:</p>
<ul>
<li>Where one spouse already had a living spouse at the time of the marriage (bigamy)</li>
<li>Where the parties are within prohibited degrees of relationship, unless a custom permits it</li>
</ul>
<p>A void marriage is treated in law as if it never existed. That raised the concern that a dependent spouse, often a woman who did not know the marriage was void, would be left without support.</p>
<h2>What the Supreme Court decided</h2>
<p>The Supreme Court has held that <strong>a spouse whose marriage is declared void can still seek permanent alimony and maintenance under Section 25</strong> of the Hindu Marriage Act.</p>
<h2>Key observations</h2>
<h3>1. "Any decree" includes a decree of nullity</h3>
<p>Section 25 allows the court to grant permanent alimony when it passes "any decree" under the Act. The Court read this broadly to include a decree declaring a marriage void.</p>
<h3>2. Financial protection continues</h3>
<p>Financial dependence does not end simply because the marriage is declared void. A dependent spouse, especially one who was unaware of the defect, should not be left without support.</p>
<h3>3. Interim maintenance under Section 24</h3>
<p>Interim maintenance and litigation expenses can also be granted while the case is pending, even if the marriage may ultimately be found void. This is discretionary and depends on the conduct of the parties.</p>
<h3>4. Dignity in language</h3>
<p>The Court criticised terms like "illegitimate wife" and "faithful mistress" as degrading, and said such language violates the right to dignity.</p>
<h2>Conclusion</h2>
<p>This ruling ensures that legal technicalities do not leave vulnerable spouses without support. Whether a marriage is valid or void, the court can consider the claim for maintenance and decide it on the facts and conduct of the parties.</p>
