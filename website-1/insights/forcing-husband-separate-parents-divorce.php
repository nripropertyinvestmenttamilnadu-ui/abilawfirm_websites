<p>Marriage is built on love, trust and respect, but it also involves balancing relationships with the wider family. In many Indian families, where joint living is common, tension can arise when one spouse insists on cutting ties with the in-laws. Can that become a ground for divorce?</p>
<h2>What the Supreme Court has said</h2>
<p>The Supreme Court has held that a wife persistently forcing her husband to separate from his parents, <strong>without a justifiable reason</strong>, can amount to <strong>mental cruelty</strong>, which is a ground for divorce under Section 13(1)(ia) of the Hindu Marriage Act, 1955.</p>
