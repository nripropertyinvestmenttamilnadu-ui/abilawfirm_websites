<li>An unreasonable demand to abandon them can put a husband under severe emotional distress.</li>
</ul>
<h3>2. Cruelty as a ground for divorce</h3>
<ul>
<li>Cruelty, mental or physical, is a recognised ground for divorce.</li>
<li>Persistent pressure that causes mental suffering can amount to cruelty, depending on the facts.</li>
</ul>
<h3>3. Living separately is not wrong in itself</h3>
<ul>
<li>The ruling does not mean a couple can never live separately from the parents. Many couples do, by mutual decision.</li>
<li>Where the demand is based on genuine concerns, such as safety, harassment or ill-treatment, the position is very different.</li>
</ul>
<h3>4. Every case turns on its facts</h3>
<ul>
