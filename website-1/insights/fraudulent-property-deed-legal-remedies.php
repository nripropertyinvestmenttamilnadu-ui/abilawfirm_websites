<p>Fraudulent property transactions can strip rightful owners of their ownership and leave them fighting for years to get it back. The law does provide remedies, but they come with strict time limits. Understanding those limits, and acting quickly, is often the difference between recovering your property and losing it.</p>
<h2>What is a fraudulent property deed?</h2>
<p>A deed is fraudulent when ownership is transferred or claimed without the true owner's consent or knowledge. Common examples include:</p>
<ul>
<li>Forged signatures on a sale or settlement deed</li>
<li>Impersonation of the owner at the Sub-Registrar office</li>
<li>A power of attorney that was forged, revoked or misused</li>
<li>Misrepresentation of facts to obtain the owner's signature</li>
</ul>
<h2>The three-year rule</h2>
<p>A suit to cancel a fraudulently registered deed must generally be filed within <strong>three years from the date the owner comes to know of the fraud</strong>. The limitation period runs from knowledge of the fraud, not from the date the deed was registered.</p>
<p>This is meant to settle disputes promptly and avoid long uncertainty over who owns a property. But it also means delay can be costly.</p>
<h2>What happens if you delay?</h2>
<p>If you wait beyond the limitation period, the court may treat the delay as acquiescence or negligence, which can seriously weaken your claim. You will need to show that any delay was for genuine reasons, such as not knowing about the fraud.</p>
<p>If a fraudulent deed comes to light many years later, it becomes much harder to persuade the court. Exceptions exist, but they are rare and need strong evidence that you genuinely did not know about the fraud until recently.</p>
<h2>What should you do?</h2>
<ul>
<li><strong>Get the Encumbrance Certificate</strong> and certified copies of the suspicious deed from the Sub-Registrar office.</li>
<li><strong>Consult a property lawyer immediately</strong>, so the right civil remedy (cancellation, declaration and injunction) is filed in time.</li>
<li><strong>Consider a criminal complaint</strong> for forgery and cheating alongside the civil case.</li>
<li><strong>Check your property regularly</strong>, especially if you live abroad or the property is vacant. A periodic EC check can catch fraud early.</li>
</ul>
<h2>Conclusion</h2>
<p>Timely action is the cornerstone of dealing with a fraudulent property deed. The three-year limitation period from the date of knowledge is a crucial safeguard. Stay vigilant, verify the status of your property regularly, and act quickly when you discover a problem.</p>
